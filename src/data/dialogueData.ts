// Local storage key for custom user-imported modules
const STORAGE_KEY_CUSTOM_MODULES = "ancient_greek_custom_modules";

export function getStoredCustomModules(): AncientGreekModule[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY_CUSTOM_MODULES);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch (err) {
    console.error("Error loading custom modules from storage:", err);
    return [];
  }
}

export function saveCustomModule(mod: AncientGreekModule): void {
  try {
    const existing = getStoredCustomModules();
    const filtered = existing.filter((m) => m.id !== mod.id);
    const updated = [mod, ...filtered];
    localStorage.setItem(STORAGE_KEY_CUSTOM_MODULES, JSON.stringify(updated));
  } catch (err) {
    console.error("Error saving custom module:", err);
  }
}

export function deleteStoredCustomModule(moduleId: string): void {
  try {
    const existing = getStoredCustomModules();
    const updated = existing.filter((m) => m.id !== moduleId);
    localStorage.setItem(STORAGE_KEY_CUSTOM_MODULES, JSON.stringify(updated));
  } catch (err) {
    console.error("Error deleting custom module:", err);
  }
}
